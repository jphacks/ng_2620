"""Writes packages/contracts/openapi.yaml from the server's routes and schemas (+ the SSE event payloads).

  python scripts/export_openapi.py [--check]     --check: exit 1 if the committed file differs
"""
import argparse
import sys
import tempfile
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
OUT = HERE.parents[2] / "packages" / "contracts" / "openapi.yaml"


def build() -> str:
    from vvlog_server.config import Settings
    from vvlog_server.interface import schemas as S
    from vvlog_server.main import create_app

    app = create_app(Settings.from_env({"VVLOG_API_TOKEN": "x", "VVLOG_DATA_ROOT": tempfile.mkdtemp()}))
    spec = app.openapi()
    spec["info"]["description"] = ("vvlog GPU server API. The source of truth is designdocs/architecture/contracts.md; "
                                   "this file is generated by services/gpu_server/scripts/export_openapi.py.")
    spec["servers"] = [{"url": "http://127.0.0.1:8765", "description": "local GPU server"},
                       {"url": "http://127.0.0.1:8766", "description": "mock server"},
                       {"url": "https://{host}", "description": "remote over Tailscale",
                        "variables": {"host": {"default": "gpu.example.ts.net"}}}]
    spec["info"]["license"] = {"name": "MIT"}
    spec["components"].setdefault("securitySchemes", {})["bearer"] = {"type": "http", "scheme": "bearer"}
    spec["security"] = [{"bearer": []}]
    spec["paths"]["/v1/health"]["get"]["security"] = []
    comps = spec["components"]["schemas"]
    events = {}
    for name, model in S.EVENT_MODELS.items():
        js = model.model_json_schema(ref_template="#/components/schemas/{model}")
        for k, v in js.pop("$defs", {}).items():
            comps.setdefault(k, v)
        comps.setdefault(model.__name__, js)
        events[name] = {"$ref": f"#/components/schemas/{model.__name__}"}
    spec["x-sse-events"] = events
    return yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=120)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            sys.exit(f"{OUT} is out of date: run python scripts/export_openapi.py")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
