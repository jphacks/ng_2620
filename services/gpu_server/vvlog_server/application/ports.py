"""Ports of the application layer (designdocs/features/gpu-server-runtime). Adapters implement them; main.py wires."""
from __future__ import annotations

from pathlib import Path
from typing import AsyncIterator, Awaitable, Callable, Protocol

from ..domain.artifact import Artifact
from ..domain.job import Job
from ..domain.media import MediaMeta, Probe
from ..domain.upload import Upload


class PipelineRunnerPort(Protocol):
    """Runs one pipeline process, streaming its output lines; terminate() kills its process group."""

    async def run(self, cmd: list[str], env: dict, cwd: Path, on_line: Callable[[str], None],
                  log_path: Path) -> int: ...

    async def terminate(self) -> None: ...


class ArtifactStorePort(Protocol):
    def publish(self, job: Job, name: str, path: Path) -> Artifact: ...
    def list(self, job_id: str) -> list[Artifact]: ...
    def open(self, job_id: str, name: str) -> tuple[Path, Artifact]: ...


class JobRepositoryPort(Protocol):
    def save(self, job: Job) -> None: ...
    def get(self, job_id: str) -> Job: ...
    def list(self, project_id: str | None = None) -> list[Job]: ...


class EventBusPort(Protocol):
    def publish(self, job_id: str, event: str, data: dict) -> int: ...
    def history(self, job_id: str, after_id: int = 0) -> list[dict]: ...
    def subscribe(self, job_id: str, after_id: int = 0) -> AsyncIterator[dict]: ...


class JobQueuePort(Protocol):
    def enqueue(self, job_id: str) -> None: ...
    def position(self, job_id: str) -> int | None: ...
    def remove(self, job_id: str) -> bool: ...
    def items(self) -> list[str]: ...


class MediaPort(Protocol):
    def probe(self, path: Path) -> Probe: ...
    def normalize(self, src: Path, meta: MediaMeta, out_full: Path, out_proxy: Path, out_audio: Path | None,
                  on_progress: Callable[[float], None]) -> None: ...
    def mux(self, video: Path, audio: Path | None, out: Path, crf: int = 18) -> None: ...


class ProjectRepositoryPort(Protocol):
    def create(self, name: str) -> dict: ...
    def get(self, project_id: str) -> dict: ...
    def save(self, project: dict) -> None: ...
    def delete(self, project_id: str) -> None: ...
    def root(self, project_id: str) -> Path: ...


class UploadRepositoryPort(Protocol):
    def save(self, upload: Upload) -> None: ...
    def get(self, upload_id: str) -> Upload: ...
    def write_chunk(self, upload: Upload, index: int, data: bytes) -> None: ...
    def assemble(self, upload: Upload, dest: Path) -> str: ...      # -> sha256 of the assembled file


class AvatarStorePort(Protocol):
    def put(self, data: bytes, filename: str) -> tuple[str, dict]: ...   # -> (avatarId, meta)
    def get(self, avatar_id: str) -> tuple[Path, dict]: ...


class PipelineOutputsPort(Protocol):
    """Turns the pipeline's output folders into contract artifacts."""

    def persons_from_masks(self, pout: Path, proxy: Path, out: Path) -> list[dict]: ...
    def latest_mesh_video(self, pout: Path) -> Path | None: ...
    def to_h264(self, src: Path, dest: Path) -> Path: ...
    def zip_layers(self, layers: Path, dest: Path) -> Path: ...


class GpuInfoPort(Protocol):
    def info(self) -> dict: ...                                      # {name, vramMB} or {}


Emit = Callable[[str, dict], Awaitable[None] | None]
